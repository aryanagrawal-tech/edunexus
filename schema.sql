-- 1. Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE,
    password_hash TEXT,
    status TEXT NOT NULL DEFAULT 'Active',
    course TEXT NOT NULL DEFAULT 'Data Structures',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Faculty Table
CREATE TABLE IF NOT EXISTS public.faculty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    department TEXT,
    status TEXT NOT NULL DEFAULT 'Active',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Admins Table
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    status TEXT NOT NULL DEFAULT 'Active',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Courses Table
CREATE TABLE IF NOT EXISTS public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name TEXT NOT NULL,
    course_code TEXT NOT NULL,
    faculty_id BIGINT REFERENCES public.faculty(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Activities Table (Supports Course Assessments & Targeted Practice Assignments)
CREATE TABLE IF NOT EXISTS public.activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    topic TEXT NOT NULL CHECK (topic IN ('Arrays', 'Linked Lists', 'Stacks', 'Queues', 'Recursion')),
    activity_type TEXT NOT NULL DEFAULT 'Quiz',
    max_score NUMERIC NOT NULL DEFAULT 100 CHECK (max_score > 0),
    instructions TEXT,
    due_date TEXT,
    assigned_student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    course_code TEXT NOT NULL DEFAULT 'CS-301',
    created_by_faculty TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Submissions Table (Supports Student Responses & Faculty Evaluation / Feedback)
CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    activity_id BIGINT NOT NULL REFERENCES public.activities(id) ON DELETE CASCADE,
    score NUMERIC NOT NULL CHECK (score >= 0 AND score <= 100),
    status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'late', 'missing', 'evaluated', 'pending_review')),
    response_text TEXT,
    feedback TEXT,
    evaluated_by TEXT,
    evaluated_at TIMESTAMP WITH TIME ZONE,
    submitted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. Course Materials Table (Unified Course Hub)
CREATE TABLE IF NOT EXISTS public.course_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    topic TEXT NOT NULL DEFAULT 'General',
    material_type TEXT NOT NULL DEFAULT 'Lecture Notes',
    resource_url TEXT,
    description TEXT,
    course_code TEXT NOT NULL DEFAULT 'CS-301',
    uploaded_by TEXT NOT NULL DEFAULT 'Faculty',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. Announcements Table (Unified Course Hub)
CREATE TABLE IF NOT EXISTS public.announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    course_code TEXT NOT NULL DEFAULT 'CS-301',
    author_name TEXT NOT NULL DEFAULT 'Faculty',
    priority TEXT NOT NULL DEFAULT 'normal',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 9. Interventions & Collaboration Table (Faculty Actions & 1-to-1 Student Support)
CREATE TABLE IF NOT EXISTS public.interventions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    student_name TEXT,
    faculty_name TEXT DEFAULT 'Course Faculty',
    course_code TEXT NOT NULL DEFAULT 'CS-301',
    topic TEXT NOT NULL DEFAULT 'General',
    intervention_type TEXT NOT NULL DEFAULT 'faculty_feedback',
    initiated_by TEXT NOT NULL DEFAULT 'faculty',
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    faculty_response TEXT,
    preferred_slot TEXT,
    status TEXT NOT NULL DEFAULT 'Open',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_submissions_student_id ON public.submissions(student_id);
CREATE INDEX IF NOT EXISTS idx_submissions_activity_id ON public.submissions(activity_id);
CREATE INDEX IF NOT EXISTS idx_activities_topic ON public.activities(topic);
CREATE INDEX IF NOT EXISTS idx_interventions_student_id ON public.interventions(student_id);

-- ====================================================================
-- Row Level Security (RLS) Configuration
-- Best practice: Enable RLS on all tables and create explicit policies.
-- ====================================================================
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.faculty ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_materials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.interventions ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY['students', 'faculty', 'admins', 'courses', 'activities', 'submissions', 'course_materials', 'announcements', 'interventions']
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = tbl AND policyname = 'Allow read access to ' || tbl) THEN
            EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT USING (true)', 'Allow read access to ' || tbl, tbl);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = tbl AND policyname = 'Allow insert access to ' || tbl) THEN
            EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT WITH CHECK (true)', 'Allow insert access to ' || tbl, tbl);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = tbl AND policyname = 'Allow update access to ' || tbl) THEN
            EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE USING (true) WITH CHECK (true)', 'Allow update access to ' || tbl, tbl);
        END IF;
    END LOOP;
END $$;

